    public static Dictionary<string, Exercise> Seed(IronMindDbContext db)
    {
        var catalog = BuildCatalog();
        var groups = new Dictionary<string, MuscleGroup>();
        var subGroups = new Dictionary<string, MuscleSubGroup>();
        var exercises = new Dictionary<string, Exercise>(StringComparer.OrdinalIgnoreCase);

        foreach (var groupEntry in catalog)
        {
            var group = new MuscleGroup { Name = groupEntry.Key };
            groups[groupEntry.Key] = group;
            db.MuscleGroups.Add(group);

            foreach (var subGroupEntry in groupEntry.Value)
            {
                var subGroupKey = $"{groupEntry.Key}:{subGroupEntry.Key}";
                var subGroup = new MuscleSubGroup
                {
                    Name = subGroupEntry.Key,
                    MuscleGroup = group
                };
                subGroups[subGroupKey] = subGroup;
                db.MuscleSubGroups.Add(subGroup);

                foreach (var exerciseEntry in subGroupEntry.Value)
                {
                    var exercise = new Exercise
                    {
                        Name = exerciseEntry.Name,
                        Description = exerciseEntry.Description,
                        MuscleSubGroup = subGroup
                    };

                    db.Exercises.Add(exercise);
                    exercises[exercise.Name] = exercise;
                }
            }
        }

        return exercises;
    }

